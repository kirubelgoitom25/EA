-- course_studio_schema  (NOT APPLIED; see README.md)
--
-- Verified against the live schema on 2026-11-02:
--   lessons.id text, modules.id text, courses.id text, profiles.id uuid,
--   quizzes.id int4, practices.id int4,
--   quizzes_lesson_id_key / practices_lesson_id_key UNIQUE(lesson_id),
--   lesson_progress_lesson_id_fkey, quiz_attempts_quiz_id_fkey,
--   practice_attempts_practice_id_fkey all ON DELETE CASCADE today.
--
-- Nothing here deletes or rewrites student data. The only change to existing
-- behaviour is step 7: history can no longer be removed by a cascade.
begin;
set local lock_timeout = '5s';

-- 0. Pre-flight: fail clean if the live shape is not what was verified -------
do $$
begin
  if exists (select 1 from information_schema.columns
             where table_schema='public' and table_name='courses' and column_name in ('owner_id','status')) then
    raise exception 'courses already migrated';
  end if;
  -- the three history FKs must exist; they are CASCADE today, or NO ACTION if this
  -- migration was applied and rolled back before (the rollback keeps NO ACTION on purpose)
  if (select count(*) from pg_constraint
      where connamespace='public'::regnamespace and confdeltype in ('c','a')
        and conname in ('lesson_progress_lesson_id_fkey','quiz_attempts_quiz_id_fkey','practice_attempts_practice_id_fkey')) <> 3 then
    raise exception 'expected the 3 history foreign keys not found';
  end if;
  if (select count(*) from pg_constraint
      where connamespace='public'::regnamespace and conname in ('quizzes_lesson_id_key','practices_lesson_id_key')) <> 2 then
    raise exception 'one-quiz/one-practice unique constraints missing';
  end if;
end $$;

-- 1. Courses: ownership, status, timestamps ------------------------------------
alter table public.courses
  add column owner_id     uuid references public.profiles(id) on delete set null,
  add column status       text not null default 'published',   -- existing rows -> published
  add column created_at   timestamptz,                         -- legacy rows stay NULL (unknown)
  add column updated_at   timestamptz not null default now(),
  add column published_at timestamptz;                         -- legacy rows stay NULL (unknown)
alter table public.courses alter column status     set default 'draft';
alter table public.courses alter column created_at set default now();
alter table public.courses
  add constraint courses_status_check check (status in ('draft','published','unpublished'));
create index courses_owner_idx  on public.courses(owner_id) where owner_id is not null;
create index courses_status_idx on public.courses(status);

-- 2. Archiving + FK-lookup indexes ------------------------------------------------
alter table public.modules add column archived_at timestamptz;
alter table public.lessons add column archived_at timestamptz;
create index modules_course_idx on public.modules(course_id);
create index lessons_module_idx on public.lessons(module_id);

-- 3. Activities ----------------------------------------------------------------------
-- (id, lesson_id) keys let an activity reference only a quiz/practice of its own lesson.
-- The existing UNIQUE(lesson_id) on quizzes/practices is kept: one quiz + one practice per lesson.
alter table public.quizzes   add constraint quizzes_id_lesson_id_key   unique (id, lesson_id);
alter table public.practices add constraint practices_id_lesson_id_key unique (id, lesson_id);

create table public.lesson_activities (
  id           integer generated by default as identity primary key,
  lesson_id    text    not null references public.lessons(id) on delete cascade,
  kind         text    not null check (kind in ('video','quiz','practice','reading')),
  sort_order   integer not null default 0 check (sort_order >= 0),
  title        text    not null check (length(btrim(title)) > 0),
  is_required  boolean not null default false,          -- nothing is required by default
  video_url    text,
  quiz_id      integer,
  practice_id  integer,
  reading_body text,
  legacy_ref   text,
  archived_at  timestamptz,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  constraint lesson_activities_legacy_ref_key unique (legacy_ref),
  constraint lesson_activities_quiz_fk
    foreign key (quiz_id, lesson_id) references public.quizzes(id, lesson_id) on delete no action,
  constraint lesson_activities_practice_fk
    foreign key (practice_id, lesson_id) references public.practices(id, lesson_id) on delete no action,
  constraint lesson_activities_payload_check check (
    (kind='video'    and video_url is not null and btrim(video_url) <> ''
                     and quiz_id is null and practice_id is null and reading_body is null) or
    (kind='quiz'     and quiz_id is not null
                     and video_url is null and practice_id is null and reading_body is null) or
    (kind='practice' and practice_id is not null
                     and video_url is null and quiz_id is null and reading_body is null) or
    (kind='reading'  and reading_body is not null
                     and video_url is null and quiz_id is null and practice_id is null)
  )
);
create unique index lesson_activities_quiz_uq     on public.lesson_activities(quiz_id)     where quiz_id is not null;
create unique index lesson_activities_practice_uq on public.lesson_activities(practice_id) where practice_id is not null;
create index lesson_activities_order_idx on public.lesson_activities(lesson_id, sort_order, id);

create table public.activity_progress (
  id           integer generated by default as identity primary key,
  student_id   uuid    not null references public.profiles(id) on delete cascade,
  activity_id  integer not null references public.lesson_activities(id) on delete no action,
  completed_at timestamptz not null default now(),
  source       text    not null default 'manual'
               check (source in ('manual','quiz_attempt','practice_attempt','backfill')),
  constraint activity_progress_student_activity_key unique (student_id, activity_id)
);
create index activity_progress_activity_idx on public.activity_progress(activity_id);

-- 4. updated_at maintenance ------------------------------------------------------------
create function public.set_updated_at() returns trigger
language plpgsql set search_path = public as $$
begin new.updated_at := now(); return new; end $$;
create trigger courses_set_updated_at before update on public.courses
  for each row execute function public.set_updated_at();
create trigger lesson_activities_set_updated_at before update on public.lesson_activities
  for each row execute function public.set_updated_at();

-- 5. lessons.video_url <-> video activities (activities are canonical) --------------------
-- The backend keeps these in step itself; the triggers are the safety net for any
-- writer that bypasses it (SQL editor, a legacy script).
create function public.sync_lesson_video(p_lesson text) returns void
language plpgsql set search_path = public as $$
declare v_url text;
begin
  select a.video_url into v_url from public.lesson_activities a
   where a.lesson_id = p_lesson and a.kind = 'video' and a.archived_at is null
   order by a.sort_order, a.id limit 1;
  update public.lessons set video_url = v_url
   where id = p_lesson and video_url is distinct from v_url;
end $$;

create function public.trg_activity_to_lesson_video() returns trigger
language plpgsql set search_path = public as $$
begin
  if TG_OP in ('INSERT','UPDATE') then perform public.sync_lesson_video(new.lesson_id); end if;
  if TG_OP = 'DELETE' or (TG_OP = 'UPDATE' and old.lesson_id <> new.lesson_id) then
    perform public.sync_lesson_video(old.lesson_id);
  end if;
  return null;
end $$;
create trigger lesson_activities_sync_video
  after insert or update or delete on public.lesson_activities
  for each row execute function public.trg_activity_to_lesson_video();

-- legacy writers that set lessons.video_url directly are mirrored into the activity layer
create function public.trg_lesson_video_to_activity() returns trigger
language plpgsql set search_path = public as $$
declare v_id integer;
begin
  if pg_trigger_depth() > 1 then return null; end if;   -- change originated from the activity sync
  if nullif(btrim(new.video_url), '') is not null then
    select id into v_id from public.lesson_activities
     where lesson_id = new.id and kind = 'video' and archived_at is null
     order by sort_order, id limit 1;
    if v_id is null then
      insert into public.lesson_activities (lesson_id, kind, sort_order, title, is_required, video_url)
      values (new.id, 'video', 0, 'Video', false, new.video_url);
    else
      update public.lesson_activities set video_url = new.video_url
       where id = v_id and video_url is distinct from new.video_url;
    end if;
  else
    update public.lesson_activities set archived_at = now()
     where lesson_id = new.id and kind = 'video' and archived_at is null;
  end if;
  return null;
end $$;
create trigger lessons_video_after_insert after insert on public.lessons
  for each row when (new.video_url is not null) execute function public.trg_lesson_video_to_activity();
create trigger lessons_video_after_update after update of video_url on public.lessons
  for each row when (old.video_url is distinct from new.video_url) execute function public.trg_lesson_video_to_activity();

revoke all on function public.set_updated_at(), public.sync_lesson_video(text),
  public.trg_activity_to_lesson_video(), public.trg_lesson_video_to_activity()
  from public, anon, authenticated;

-- 6. New tables: backend / service role only -------------------------------------------------
alter table public.lesson_activities enable row level security;
alter table public.activity_progress enable row level security;
revoke all on table public.lesson_activities, public.activity_progress from public, anon, authenticated;
revoke all on sequence public.lesson_activities_id_seq, public.activity_progress_id_seq from public, anon, authenticated;
grant all on table public.lesson_activities, public.activity_progress to service_role;
grant usage, select on sequence public.lesson_activities_id_seq, public.activity_progress_id_seq to service_role;

-- 7. Historical data protection (approved): history can no longer be cascade-deleted ----------
alter table public.lesson_progress
  drop constraint lesson_progress_lesson_id_fkey,
  add  constraint lesson_progress_lesson_id_fkey
       foreign key (lesson_id) references public.lessons(id) on delete no action;
alter table public.quiz_attempts
  drop constraint quiz_attempts_quiz_id_fkey,
  add  constraint quiz_attempts_quiz_id_fkey
       foreign key (quiz_id) references public.quizzes(id) on delete no action;
alter table public.practice_attempts
  drop constraint practice_attempts_practice_id_fkey,
  add  constraint practice_attempts_practice_id_fkey
       foreign key (practice_id) references public.practices(id) on delete no action;

-- 8. Post-checks (roll back the whole migration if any fail) ----------------------------------
do $$
begin
  if not has_table_privilege('service_role','public.lesson_activities','select,insert,update,delete')
     or not has_table_privilege('service_role','public.activity_progress','select,insert,update,delete')
     or not has_sequence_privilege('service_role','public.lesson_activities_id_seq','usage')
     or not has_sequence_privilege('service_role','public.activity_progress_id_seq','usage')
  then raise exception 'service_role lacks access to new objects'; end if;

  if has_table_privilege('anon','public.lesson_activities','select')
     or has_table_privilege('authenticated','public.lesson_activities','select')
     or has_table_privilege('anon','public.activity_progress','select')
     or has_table_privilege('authenticated','public.activity_progress','select')
  then raise exception 'anon/authenticated can access new tables'; end if;

  if (select count(*) from pg_constraint where connamespace='public'::regnamespace and confdeltype<>'a'
        and conname in ('lesson_progress_lesson_id_fkey','quiz_attempts_quiz_id_fkey','practice_attempts_practice_id_fkey')) > 0
  then raise exception 'history FKs still cascade'; end if;

  if (select count(*) from public.courses where status<>'published' or owner_id is not null) > 0
  then raise exception 'legacy courses not ownerless+published'; end if;
end $$;

commit;
